faltas as (
  -- tabelas que não existem
  select 1 as ordem, 'Falta a tabela' as problema, e.tabela as item,
         coalesce((select case when arquivo='telas' then 'criada pelos SQLs originais da plataforma' else 'rode '||arquivo end from origem o where o.tabela=e.tabela),'') as como_resolver
    from (select distinct tabela from esperado) e
   where to_regclass('public.'||e.tabela) is null
  union all
  -- colunas que não existem (em tabelas que existem)
  select 2, 'Falta a coluna', e.tabela||'.'||e.coluna,
         coalesce((select case when arquivo='telas' then 'criada pelos SQLs originais da plataforma' else 'rode '||arquivo end from origem o where o.tabela=e.tabela),'')
    from esperado e
   where to_regclass('public.'||e.tabela) is not null
     and not exists (select 1 from information_schema.columns c
                      where c.table_schema='public' and c.table_name=e.tabela and c.column_name=e.coluna)
  union all
  -- funções usadas pelas regras de acesso e pela auditoria
  select 3, 'Falta a função', f.nome, 'criada nos SQLs da plataforma'
    from (values ('clinica_papel_atual'), ('clinica_tg_auditar'), ('acomp_papel'), ('acomp_nome'), ('acomp_receber_forms'), ('acomp_vincular_paciente'), ('acomp_sync_pendencias'), ('acomp_etapa_sugerida'), ('acomp_norm'), ('acomp_tel')) f(nome)
   where not exists (select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname=f.nome)
  union all
  -- gatilhos que ligam o Forms à jornada e mantêm a auditoria
  select 3, 'Falta o gatilho', g.tabela||' → '||g.nome, 'rode '||g.arquivo
    from (values ('clinica_acompanhamentos','acomp_vincular','forms-jornada.sql'), ('clinica_acompanhamentos','acomp_pendencias','forms-jornada.sql'), ('clinica_pendencias','acomp_pend_volta','forms-jornada.sql'), ('clinica_realizados','tg_aud_realizados','realizados-schema.sql'), ('clinica_pacientes','tg_aud_pacientes','SQLs originais da plataforma')) g(tabela,nome,arquivo)
   where to_regclass('public.'||g.tabela) is not null
     and not exists (select 1 from pg_trigger t where t.tgrelid=to_regclass('public.'||g.tabela) and t.tgname=g.nome)
  union all
  -- tabelas sem RLS ligado (dados expostos)
  select 4, 'RLS desligado', e.tabela, 'alter table public.'||e.tabela||' enable row level security;'
    from (select distinct tabela from esperado) e
    join pg_class c on c.oid=to_regclass('public.'||e.tabela)
   where not c.relrowsecurity
  union all
  -- pasta de arquivos (Storage)
  select 5, 'Falta a pasta de arquivos', b.nome, 'Storage → New bucket'
    from (values ('comprovantes')) b(nome)
   where not exists (select 1 from storage.buckets s where s.id=b.nome)
)
select problema, item, como_resolver from faltas
union all
select '✓ Tudo certo', 'o banco tem tudo o que a plataforma usa', '' where not exists (select 1 from faltas)
order by 1, 2;
